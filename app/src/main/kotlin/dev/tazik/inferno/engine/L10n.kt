        for ((k, v) in l10nUaPairs) if (!containsKey(k)) put(k, v)
    }

    /** `%@` из Swift — это `%s` в `String.format`. */
    fun string(russian: String): String {
        val target = when (showEnglishOverride) {
            null -> resolved
            true -> AppLanguage.EN
            false -> return russian
        }
        if (target == AppLanguage.RU) return russian
        val translated = when (target) {
            AppLanguage.UA -> ukTable[russian]
            else -> table[russian]
        }
        return (translated ?: russian).replace("%@", "%s")
    }

    fun format(russian: String, args: Array<out Any?>): String {
        if (args.isEmpty()) return string(russian)
        // Формат в исходнике — Swift-овский: %@ вместо %s и модификатор
        // длины «ll», которого Java не знает. Переводим оба, дальше — обычный
        // String.format; на любую несовместимость отвечаем непереведённой
        // строкой, как и раньше.
        val pattern = lengthModifier
            .replace(string(russian).replace("%@", "%s")) { match ->
                "%" + match.groupValues[1] + match.groupValues[2]
            }
        return try {
            String.format(Locale.ROOT, pattern, *args)
        } catch (_: Throwable) {
            string(russian)
        }
    }

    /** `%lld`, `%llx`, `%llu` — Swift говорит «длинное», Java берёт размер из
     * типа аргумента: модификатор просто снимается.
     */
    private val lengthModifier = Regex("%([0-9.#+\\- ]*)ll([diouxX])")
}

fun L(russian: String): String = L10n.string(russian)

fun L(russian: String, vararg args: Any?): String = L10n.format(russian, args)
