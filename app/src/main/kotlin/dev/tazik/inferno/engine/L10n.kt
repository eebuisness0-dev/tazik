     * а не после следующей перекомпоновки по другой причине.
     */
    var language: AppLanguage by mutableStateOf(AppLanguage.SYSTEM)

    @Volatile
    var showEnglishOverride: Boolean? = null

    /** Язык, на который реально переводим: «Системный» разворачивается по
     * локали телефона, украинская локаль получает украинский, русская —
     * русский, всё прочее — английский. (Код украинского в ISO-локали —
     * «uk», у нас же собственный код — «ua».)
     */
    val resolved: AppLanguage
        get() = when (language) {
            AppLanguage.SYSTEM -> when (Locale.getDefault().language) {
                "uk" -> AppLanguage.UA
                "ru" -> AppLanguage.RU
                else -> AppLanguage.EN
            }
            else -> language
        }

    val showEnglish: Boolean
        get() = showEnglishOverride ?: resolved != AppLanguage.RU

