/**
 * Порт `L10n.swift`.
 *
 * Строки написаны по-русски в исходнике и переводятся на выходе: так
 * непереведённая строка падает обратно в оригинал, а не показывает ключ.
 * Целевых языка три — английский и украинский (русский и есть оригинал);
 * у каждого своя таблица пар, а не словарь: повтор ключа — это просто
 * повтор, побеждает первый (в Swift литерал словаря с повтором падал на
 * первом же английском слове).
 */
enum class AppLanguage(val code: String) {
    SYSTEM("system"), RU("ru"), EN("en"), UA("ua");

    val title: String
        get() = when (this) {
            SYSTEM -> L("Системный")
            RU -> "Русский"
            EN -> "English"
            UA -> "Українська"
        }

    companion object {
        fun of(code: String): AppLanguage = entries.firstOrNull { it.code == code } ?: SYSTEM
    }
}

object L10n {
    /** Текущий язык — snapshot-состояние: композиции, вызывающие `L()`,
